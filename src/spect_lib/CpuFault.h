#ifndef SPECT_LIB_CPU_FAULT_H_
#define SPECT_LIB_CPU_FAULT_H_

#include "spect.h"

class spect::CpuFault
{
    public:

        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @section Control functions
        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Default CPU Fault constructor
        /// @returns New fault object
        ///////////////////////////////////////////////////////////////////////////////////////////
        CpuFault();

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief New CPU Fault constructor
        /// @param inst_addr instruction address when the fault shall be applied
        /// @param inst_exec_cnt number of executions of the instruction, after which the fault
        ///        shall be applied
        /// @param fault_data tha value the insdtruction code shall be replaced with
        /// @returns New fault object
        ///////////////////////////////////////////////////////////////////////////////////////////
        CpuFault(
            uint32_t            inst_addr,
            uint32_t            inst_exec_cnt,
            uint32_t            fault_data,
            const std::string   description
        );

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief New CPU Fault constructor
        /// @param path path to Fault Config File
        /// @returns New fault object
        ///////////////////////////////////////////////////////////////////////////////////////////
        CpuFault(const std::string &path);

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Cpu Fault descructor
        ///////////////////////////////////////////////////////////////////////////////////////////
        ~CpuFault();

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Check if fault shall be applied
        ///////////////////////////////////////////////////////////////////////////////////////////
        bool Check(const uint32_t addr, const uint32_t exec_cnt);

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Cpu Fault Checker
        ///////////////////////////////////////////////////////////////////////////////////////////
        void Apply(uint32_t *wrd);

        // verbosity
        uint32_t    verbosity_ = 0;

        // Print function
        int (*print_fnc)(const char *format, ...);

    private:
        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @section Private attributes
        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////
        uint32_t    m_inst_addr;
        uint32_t    m_inst_exec_cnt;
        uint32_t    m_fault_data;
        std::string m_description;

        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @section Private methods
        ///////////////////////////////////////////////////////////////////////////////////////////
        ///////////////////////////////////////////////////////////////////////////////////////////
        void PrintArgs();

        template<typename Arg>
        void PrintArgs(Arg arg);

        template<typename First, typename... Args>
        void PrintArgs(First first, Args... args);

        ///////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Print debug fault message
        /// @param verbosity_level Verbosity of the message
        ///         VERBOSITY_NONE      - Always shown
        ///         VERBOSITY_LOW       - Shown when verbosity is 1 or higher
        ///         VERBOSITY_MEDIUM    - Shown when verbosity is 2 or higher
        ///         VERBOSITY_HIGH      - Shown when verbosity is 3 or higher
        ///////////////////////////////////////////////////////////////////////////////////////////
        template<class... T>
        void DebugInfo(uint32_t verbosity_level, const T ...args);
};

#endif